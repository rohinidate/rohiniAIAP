package myPack;

public class Assignment_4 {

	// Write a program on +,-,*,/ and % operators
	public static void main(String[] args) {

		int a = 100;
		int b = 20;
		int c = a + b;
		int d = a - b;
		int e = a * b;
		int f = a / b;
		int g = a % b;
		System.out.println("Addition Operation: " + c);
		System.out.println("Substraction Operation: " + d);
		System.out.println("Multiplication Operation: " + e);
		System.out.println("Division Operation: " + f);
		System.out.println("Modulo Operation: " + g);

	}

}
